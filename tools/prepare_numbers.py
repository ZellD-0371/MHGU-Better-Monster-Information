"""Preformat the exact numeric values used by the database, without runtime allocations."""
from pathlib import Path
import re,struct,json,hashlib,argparse
ROOT=Path(__file__).resolve().parents[1]
def f32(v):return struct.unpack('<f',struct.pack('<f',v))[0]
def number(v):
 if v<0:return '—'
 if v==int(v):return str(int(v))
 scaled=int(f32(f32(v*100000)+0.5));return str(scaled//100000)+'.'+str(scaled%100000).zfill(5).rstrip('0')
def percent(v):
 if v==-1:return '—'
 if v==-2:return '…'
 if v%100==0:return f'{v//100}%'
 return f'{v//100}.{v%100:02}%'
def generate(check=False):
 source=(ROOT/'src/generated.rs').read_text(encoding='utf-8');values={}
 for row in re.findall(r'values:\[([^]]+)\]',source):
  for word in row.split(','):
   value=f32(float(word));bits=struct.unpack('<I',struct.pack('<f',value))[0];values[bits]=value
 percents={-1,-2}
 for row in re.findall(r'cells:\[([^]]+)\]',source):percents.update(map(int,row.split(',')))
 percents.update(map(int,re.findall(r'percent:(\d+)',source)))
 lines=['// Generated by tools/prepare_numbers.py.','pub static NUMBERS:&[(u32,&str)]=&[']
 lines += [f'({bits},{json.dumps(number(v),ensure_ascii=False)}),' for bits,v in sorted(values.items())]
 lines += ['];','pub static PERCENTS:&[(i16,&str)]=&[']+[f'({v},{json.dumps(percent(v),ensure_ascii=False)}),' for v in sorted(percents)]+['];']
 data='\n'.join(lines)+'\n';out=ROOT/'src/numeric_generated.rs'
 if check:assert out.read_text(encoding='utf-8')==data,'Numeric resources stale; run tools/prepare_numbers.py'
 else:out.write_text(data,encoding='utf-8')
 print(f'Numeric table: {len(values)} numbers, {len(percents)} percentages; {len(data.encode())} source bytes')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();generate(a.check)
