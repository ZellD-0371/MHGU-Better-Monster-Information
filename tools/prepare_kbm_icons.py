"""Pack the keyboard / mouse prompt pictures into their own small atlas (Recomp only; the monster atlas is unchanged).

Source: Kenney Input Prompts (CC0 - www.kenney.nl), "Keyboard & Mouse" Default (64x64), in ../HD Icons/kenney Icons.
Names follow button_prompts::key_sprite: the Recomp [Keybinds] key name (SDL3 key names, "Mouse Left", "Wheel Up")
in lower case, spaces as '-', punctuation as words. Names with two spellings are folded in key_sprite.

Writes assets/native/kbm-icons.rgba (48 px cells), assets/native-low/kbm-icons.rgba (32 px cells) and src/generated_kbm.rs.
"""
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'HD Icons' / 'kenney Icons' / 'Keyboard & Mouse' / 'Default'
# Kenney pictures leave a wide margin (visible part 48 of 64): crop the same centered 56x56 from every picture.
CROP = (4, 4, 60, 60)
WIDTH = 512
VARIANTS = {'standard': ('assets/native', 48), 'low-memory': ('assets/native-low', 32)}

MAP = {}
for c in 'abcdefghijklmnopqrstuvwxyz0123456789':
    MAP[c] = f'keyboard_{c}'
for n in range(1, 13):
    MAP[f'f{n}'] = f'keyboard_f{n}'
MAP.update({
    'up': 'keyboard_arrow_up', 'down': 'keyboard_arrow_down', 'left': 'keyboard_arrow_left', 'right': 'keyboard_arrow_right',
    'space': 'keyboard_space', 'return': 'keyboard_enter', 'keypad-enter': 'keyboard_numpad_enter',
    'keypad-plus': 'keyboard_numpad_plus', 'keypad-asterisk': 'keyboard_asterisk',
    'backspace': 'keyboard_backspace', 'tab': 'keyboard_tab', 'escape': 'keyboard_escape',
    'left-shift': 'keyboard_shift', 'right-shift': 'keyboard_shift', 'left-ctrl': 'keyboard_ctrl', 'right-ctrl': 'keyboard_ctrl',
    'left-alt': 'keyboard_alt', 'right-alt': 'keyboard_alt', 'left-gui': 'keyboard_win',
    'capslock': 'keyboard_capslock', 'pageup': 'keyboard_page_up', 'pagedown': 'keyboard_page_down',
    'home': 'keyboard_home', 'end': 'keyboard_end', 'insert': 'keyboard_insert', 'delete': 'keyboard_delete',
    'numlock': 'keyboard_numlock', 'printscreen': 'keyboard_printscreen', 'scrolllock': 'keyboard_scroll_lock',
    'pause': 'keyboard_pause',
    'minus': 'keyboard_minus', 'equals': 'keyboard_equals', 'bracket-open': 'keyboard_bracket_open',
    'bracket-close': 'keyboard_bracket_close', 'semicolon': 'keyboard_semicolon', 'apostrophe': 'keyboard_apostrophe',
    'comma': 'keyboard_comma', 'period': 'keyboard_period', 'slash': 'keyboard_slash_forward',
    'backslash': 'keyboard_slash_back', 'grave': 'keyboard_tilde',
    'mouse-left': 'mouse_left', 'mouse-right': 'mouse_right', 'mouse-middle': 'mouse_scroll',
    'mouse-4': 'mouse_side_back', 'mouse-5': 'mouse_side_forward',
    'wheel-up': 'mouse_scroll_up', 'wheel-down': 'mouse_scroll_down',
})


# Kenney key caps are white with see-through letters, which vanish on BMI's light paper panels. Fill the enclosed
# holes (letters, symbols) with ink and add a thin ink rim, so a cap reads on paper and on the black prompt bar alike.
INK = (40, 42, 43, 255)


def ink(im):
    from PIL import ImageChops, ImageDraw, ImageFilter
    w, h = im.size
    alpha = im.getchannel('A')
    solid = alpha.point(lambda v: 255 if v >= 128 else 0)
    # Outside = transparent pixels reachable from the border; anything else not solid is a hole
    outside = solid.copy()
    for seed in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
        if outside.getpixel(seed) == 0:
            ImageDraw.floodfill(outside, seed, 128)
    outside = outside.point(lambda v: 255 if v == 128 else 0)
    shape = ImageChops.invert(outside).filter(ImageFilter.GaussianBlur(0.6))
    rim = shape.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(0.6))
    base = Image.new('RGBA', im.size, INK[:3] + (0,))
    base.putalpha(rim)
    base.alpha_composite(im)
    return base


def main():
    if not SOURCE.is_dir():
        sys.exit(f'missing {SOURCE}')
    stems = sorted(set(MAP.values()))
    cells = {stem: i for i, stem in enumerate(stems)}
    names = sorted(MAP)
    code = ['// Generated by tools/prepare_kbm_icons.py. Do not edit.',
            '// Keyboard / mouse prompt pictures: Kenney Input Prompts (CC0, www.kenney.nl).',
            f'pub static NAMES:[(&str,u8);{len(names)}]=[' + ','.join(f'({json.dumps(n)},{cells[MAP[n]]})' for n in names) + '];']
    summary = {'names': len(names), 'pictures': len(stems)}
    for variant, (folder, cell) in VARIANTS.items():
        step = cell + 2
        columns = WIDTH // step
        height = -(-len(stems) // columns) * step
        atlas = Image.new('RGBA', (WIDTH, height))
        for i, stem in enumerate(stems):
            im = ink(Image.open(SOURCE / f'{stem}.png').convert('RGBA')).crop(CROP).resize((cell, cell), Image.Resampling.LANCZOS)
            atlas.paste(im, (1 + i % columns * step, 1 + i // columns * step))
        out = ROOT / folder
        out.mkdir(exist_ok=True)
        (out / 'kbm-icons.rgba').write_bytes(atlas.tobytes())
        cfg = 'not(bmi_low_memory)' if variant == 'standard' else 'bmi_low_memory'
        code.append(f'#[cfg({cfg})]pub const CELL:usize={cell};#[cfg({cfg})]pub const COLUMNS:usize={columns};#[cfg({cfg})]pub const TEX_H:usize={height};')
        summary[variant] = {'cell': cell, 'size': [WIDTH, height], 'bytes': WIDTH * height * 4}
    code += [f'pub const TEX_W:usize={WIDTH};',
             '/// Picture cell of a key_sprite name',
             'pub fn find(name:&str)->Option<usize>{NAMES.binary_search_by(|(n,_)|(*n).cmp(name)).ok().map(|i|NAMES[i].1 as usize)}']
    (ROOT / 'src/generated_kbm.rs').write_text('\n'.join(code) + '\n', encoding='utf-8')
    print(json.dumps(summary))


if __name__ == '__main__':
    main()
