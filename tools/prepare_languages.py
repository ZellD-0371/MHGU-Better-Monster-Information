"""Split all text by language and generate a metric-preserving shared Noto subset."""
from pathlib import Path
import json,struct,re,zlib,hashlib,argparse
ROOT=Path(__file__).resolve().parents[1]
CODES=['en','zh-Hans','zh-Hant','ja','ko','de','fr','it','es']
def build(check=False):
 blob=(ROOT/'assets/native/monster-text.bin').read_bytes();assert blob[:8]==b'BMITXT01'
 count=struct.unpack_from('<I',blob,8)[0];texts=[]
 for i in range(count):
  values=[]
  for l in range(9):
   at=struct.unpack_from('<I',blob,12+i*36+l*4)[0];values.append(blob[at:blob.index(0,at)].decode('utf-8'))
  texts.append(values)
 # Progression expressions are identical in all languages and can use the active pack.
 generated=(ROOT/'src/generated.rs').read_text(encoding='utf-8')
 ruleline=re.search(r'pub static RULES:[^\n]+',generated)[0]
 for _,idx in re.findall(r'\((\d+),(\d+)\)',ruleline):assert len(set(texts[int(idx)]))==1
 chars=set(range(32,127))|{0xa0}
 for values in texts:
  for t in values:chars.update(ord(c) for c in t if ord(c)>=32)
 for p in (ROOT/'src').glob('*.rs'):
  # purplelib.rs text is drawn by the game's font (Options > Mod Options), not ours
  if p.name.startswith(('generated','language_assets','skin_generated','purplelib')):continue
  for literal in re.findall(r'"(?:[^"\\]|\\.)*"',p.read_text(encoding='utf-8')):
   try:t=json.loads(literal)
   except ValueError:continue
   chars.update(ord(c) for c in t if ord(c)>=32)
 original=ROOT/'assets/NotoSansCJKkr-Regular.otf';out=ROOT/'assets/languages';out.mkdir(exist_ok=True)
 digest=hashlib.sha256(blob+original.read_bytes()+json.dumps(sorted(chars)).encode()+Path(__file__).read_bytes()).hexdigest()
 mf=out/'manifest.json';old=json.loads(mf.read_text(encoding='utf-8')) if mf.exists() else {}
 if old.get('inputs_sha256')==digest and all((out/n).exists() and (d:=(out/n).read_bytes()) and len(d)==v['bytes'] and zlib.crc32(d)==v['crc32'] for n,v in old['files'].items()):emit(old);return old
 if check:raise SystemExit('Stale language/font resources; regenerate with fontTools.')
 files={}
 for l,code in enumerate(CODES):
  pool=bytearray();index=bytearray();offsets={};header=16+count*4
  for values in texts:
   t=values[l]
   if t not in offsets:offsets[t]=header+len(pool);pool+=t.encode()+b'\0'
   index+=struct.pack('<I',offsets[t])
  data=b'BMILANG1'+struct.pack('<II',count,l)+index+pool;name=f'text.{code}.bin';(out/name).write_bytes(data);files[name]={'bytes':len(data),'crc32':zlib.crc32(data)}
 from fontTools import subset
 from fontTools.ttLib import TTFont
 source=TTFont(original,recalcTimestamp=False);cmap=source.getBestCmap();missing=sorted(chars-cmap.keys());assert not missing,missing
 font=TTFont(original,recalcTimestamp=False);opts=subset.Options();opts.layout_features=['*'];opts.recalc_timestamp=False;opts.notdef_glyph=True;opts.notdef_outline=True;opts.recommended_glyphs=True
 worker=subset.Subsetter(options=opts);worker.populate(unicodes=chars);worker.subset(font)
 family='Better Monster Information UI';ps='BetterMonsterInformationUI-Regular'
 font['name'].names=[n for n in font['name'].names if n.nameID not in (1,2,3,4,6,16,17)]
 for i,value in [(1,family),(2,'Regular'),(3,ps+'-1'),(4,family+' Regular'),(6,ps),(16,family),(17,'Regular')]:font['name'].setName(value,i,3,1,0x409)
 if 'CFF ' in font:
  cff=font['CFF '].cff;cff.fontNames=[ps];cff.topDictIndex[0].FamilyName=family;cff.topDictIndex[0].FullName=family+' Regular'
 name='font.shared.otf';font.save(out/name);verified=TTFont(out/name);cm=verified.getBestCmap();assert chars<=cm.keys()
 assert all(verified['hmtx'][cm[c]]==source['hmtx'][cmap[c]] for c in chars)
 assert (verified['hhea'].ascent,verified['hhea'].descent)==(source['hhea'].ascent,source['hhea'].descent)
 data=(out/name).read_bytes();files[name]={'bytes':len(data),'crc32':zlib.crc32(data)}
 result={'inputs_sha256':digest,'codes':CODES,'count':count,'characters':len(chars),'original_font_bytes':original.stat().st_size,'files':files};mf.write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8');emit(result);return result
def emit(m):
 lines=['// Generated by tools/prepare_languages.py.','pub const COUNT:usize='+str(m['count'])+';','pub const FILES:[(usize,u32);9]=[']
 for code in CODES:
  f=m['files'][f'text.{code}.bin'];lines.append(f"({f['bytes']},{f['crc32']}),")
 f=m['files']['font.shared.otf'];lines+= ['];',f"pub const FONT:(usize,u32)=({f['bytes']},{f['crc32']});"]
 (ROOT/'src/language_assets.rs').write_text('\n'.join(lines)+'\n',encoding='utf-8')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();m=build(a.check);print(json.dumps(m,ensure_ascii=False))

